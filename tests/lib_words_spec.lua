--- Numbers as people read them (shared/words.lua): the exact words the
--- notices, command answers and panel lines have always used.

local Words = require('crimson-hitman.shared.words')

describe('Words: money, hours, waits and distances', function()
    it('writes dollars grouped, a negative the way each reader has always seen it', function()
        eq(Words.dollars(0), '$0')
        eq(Words.dollars(1000), '$1,000')
        eq(Words.dollars(1234567.9), '$1,234,567')
        eq(Words.dollars(-1500), '$-1,500', 'staff lines and summaries')
        eq(Words.dollars('nonsense'), '$0')
        eq(Words.dollars(-1500, 'before'), '-$1,500', 'a player\'s notice')
        eq(Words.dollars(15000, 'before'), '$15,000')
        eq(Words.dollars(-1500, 'none'), '$1,500', 'the amount alone')
        eq(Words.dollars(999, 'none'), '$999')
        eq(Words.dollars(nil, 'before'), '$0')
    end)

    it('writes hours to a tenth, rounded first unless asked for the exact figure', function()
        eq(Words.hours(3), '3 h')
        eq(Words.hours(2.5), '2.5 h')
        eq(Words.hours(2.96), '3 h', 'rounded to the tenth first')
        eq(Words.hours(2.04), '2 h')
        eq(Words.hours(nil), '0 h')
        eq(Words.hours(3, true), '3 h')
        eq(Words.hours(2.96, true), '3.0 h', 'exact: not rounded first')
        eq(Words.hours(0.5, true), '0.5 h')
    end)

    it('writes a length of time in seconds under a minute, minutes rounded up after', function()
        eq(Words.duration(1), '1 second')
        eq(Words.duration(45), '45 seconds')
        eq(Words.duration(60), '1 minute')
        eq(Words.duration(61), '2 minutes')
        eq(Words.duration(-5), '0 seconds')
        eq(Words.duration('x'), '0 seconds')
    end)

    it('writes when to try again', function()
        eq(Words.inAbout(0), 'in a moment')
        eq(Words.inAbout(nil), 'in a moment')
        eq(Words.inAbout(0 / 0), 'in a moment', 'NaN')
        eq(Words.inAbout(0.2), 'in 1 second')
        eq(Words.inAbout(30), 'in 30 seconds')
        eq(Words.inAbout(60), 'in about 1 minute')
        eq(Words.inAbout(121), 'in about 3 minutes')
    end)

    it('writes metres whole when whole, else to one decimal', function()
        eq(Words.metres(12), '12')
        eq(Words.metres(12.0), '12', 'not "12.0"')
        eq(Words.metres(7.5), '7.5')
        eq(Words.metres('10'), '10')
        eq(Words.metres(nil), '0')
        eq(Words.metres(1e12), '1000000000000.0', 'a number too big for %d never raises')
    end)
end)
