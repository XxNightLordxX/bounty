--- The per-day (per-window) counter (server/lib/window.lua, Window.new):
--- counts inside a sliding window, the check and the count as one step.
--- Used by the staff alert thresholds (server/thresholds.lua).

local Window = require('server.lib.window')

describe('Window: counts inside a sliding window', function()
    it('counts what is inside the window and forgets what fell out of it', function()
        local day = Window.new(86400)
        eq(day.count('A', 1000), 0, 'nothing before the first')
        eq(day.add('A', 1000), 1)
        eq(day.add('A', 2000), 2)
        eq(day.count('A', 2000), 2)
        eq(day.count('A', 1000 + 86399), 2, 'a second before the first falls out')
        eq(day.count('A', 1000 + 86400), 1, 'the first is out at exactly a day')
        eq(day.count('B', 2000), 0, 'keys are counted apart')
        eq(day.seconds, 86400)
    end)

    it('keeps at most `keep` of the newest', function()
        local w = Window.new(3600)
        for t = 1, 10 do w.add('A', t, 3) end
        eq(w.count('A', 10), 3)
        eq(w.get('A').times[1], 8, 'the oldest dropped first')
    end)

    it('takes one only while fewer than the limit are inside, check and count as one', function()
        local w = Window.new(60)
        local ok, n = w.take('cap', 2, 100)
        truthy(ok)
        eq(n, 1)
        ok, n = w.take('cap', 2, 101)
        truthy(ok)
        eq(n, 2)
        ok, n = w.take('cap', 2, 102)
        falsy(ok, 'the third is refused')
        eq(n, 2, 'and not counted')
        ok = w.take('cap', 2, 160)
        truthy(ok, 'one fell out at a minute, so there is room again')
        falsy(w.take('zero', 0, 100), 'a limit of 0 takes nothing')
    end)

    it('keeps what a caller writes beside the times', function()
        local w = Window.new(60)
        eq(w.get('A'), nil)
        w.add('A', 5)
        w.get('A').alertedAt = 5
        w.add('A', 6)
        eq(w.get('A').alertedAt, 5, 'kept across counts')
    end)

    it('sweeps keys with nothing inside, unless keepIf says to keep them', function()
        local w = Window.new(60)
        w.add('old', 0)
        w.add('kept', 0)
        w.get('kept').alertedAt = 50
        w.add('fresh', 100)
        local dropped = w.sweep(105, function(entry, now) return entry.alertedAt ~= nil and now - entry.alertedAt < 60 end)
        eq(dropped, 1, 'only the old one')
        eq(w.get('old'), nil)
        truthy(w.get('kept'))
        truthy(w.get('fresh'))
        eq(w.sweep(1000), 2, 'and the rest once they run out')
    end)

    it('clears one key or all of them, and survives a nonsense window', function()
        local w = Window.new(60)
        w.add('A', 1)
        w.add('B', 1)
        w.clear('A')
        eq(w.count('A', 1), 0)
        eq(w.count('B', 1), 1)
        w.reset()
        eq(w.count('B', 1), 0)
        local bad = Window.new('nonsense')
        eq(bad.seconds, 1, 'at least a second')
        eq(bad.add('A', 1), 1)
        eq(bad.count('A', 2), 0)
    end)

    it('counts by os.time() when no time is given', function()
        local w = Window.new(60)
        w.add('A')
        eq(w.count('A'), 1)
    end)
end)
